-- EV Charging Network Management System
-- Step 3: Create the 14 core PostgreSQL tables
-- Run this script while connected to the ev_charging_network database.

BEGIN;

-- 1. USERS: customers, station operators, and administrators
CREATE TABLE users (
    user_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    phone         VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER'
                  CHECK (role IN ('CUSTOMER', 'OPERATOR', 'ADMIN')),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 2. CONNECTOR_TYPES: connector standards supported by the network
CREATE TABLE connector_types (
    connector_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_name         VARCHAR(60) NOT NULL UNIQUE,
    description       VARCHAR(255)
);

-- 3. VEHICLES: electric vehicles registered by users
CREATE TABLE vehicles (
    vehicle_id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id        BIGINT NOT NULL REFERENCES users(user_id),
    registration_number  VARCHAR(30) NOT NULL UNIQUE,
    make                 VARCHAR(60) NOT NULL,
    model                VARCHAR(80) NOT NULL,
    battery_capacity_kwh NUMERIC(7,2),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (battery_capacity_kwh IS NULL OR battery_capacity_kwh > 0)
);

-- 4. VEHICLE_CONNECTOR_TYPES: resolves the many-to-many vehicle/connector relation
CREATE TABLE vehicle_connector_types (
    vehicle_id        BIGINT NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE CASCADE,
    connector_type_id INTEGER NOT NULL REFERENCES connector_types(connector_type_id),
    PRIMARY KEY (vehicle_id, connector_type_id)
);

-- 5. STATIONS: charging station location and operator details
CREATE TABLE stations (
    station_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operator_id   BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    station_name  VARCHAR(120) NOT NULL,
    address       VARCHAR(255) NOT NULL,
    city          VARCHAR(80) NOT NULL,
    latitude      NUMERIC(10,7),
    longitude     NUMERIC(10,7),
    opening_time  TIME,
    closing_time  TIME,
    status        VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                  CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

-- 6. CHARGERS: individually reservable charging ports
CREATE TABLE chargers (
    charger_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id         BIGINT NOT NULL REFERENCES stations(station_id),
    connector_type_id  INTEGER NOT NULL REFERENCES connector_types(connector_type_id),
    charger_code       VARCHAR(40) NOT NULL,
    power_kw           NUMERIC(7,2) NOT NULL CHECK (power_kw > 0),
    operational_status VARCHAR(25) NOT NULL DEFAULT 'ONLINE'
                       CHECK (operational_status IN ('ONLINE', 'MAINTENANCE', 'OUT_OF_SERVICE')),
    UNIQUE (station_id, charger_code)
);

-- 7. TARIFFS: base charging prices and validity period
CREATE TABLE tariffs (
    tariff_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_id         BIGINT NOT NULL REFERENCES stations(station_id),
    connector_type_id  INTEGER REFERENCES connector_types(connector_type_id),
    base_price_per_kwh NUMERIC(10,2) NOT NULL CHECK (base_price_per_kwh >= 0),
    session_fee        NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (session_fee >= 0),
    tax_rate_percent   NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (tax_rate_percent BETWEEN 0 AND 100),
    valid_from         TIMESTAMPTZ NOT NULL,
    valid_to           TIMESTAMPTZ,
    CHECK (valid_to IS NULL OR valid_to > valid_from)
);

-- 8. PRICING_RULES: configurable time-based or demand-based price adjustments
CREATE TABLE pricing_rules (
    rule_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tariff_id                 BIGINT NOT NULL REFERENCES tariffs(tariff_id) ON DELETE CASCADE,
    rule_type                 VARCHAR(30) NOT NULL
                              CHECK (rule_type IN ('PEAK_HOUR', 'OFF_PEAK', 'HIGH_DEMAND')),
    start_time                TIME,
    end_time                  TIME,
    demand_threshold_percent  NUMERIC(5,2),
    price_multiplier          NUMERIC(6,3) NOT NULL DEFAULT 1.000 CHECK (price_multiplier > 0),
    priority                  INTEGER NOT NULL DEFAULT 1,
    is_active                 BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (demand_threshold_percent IS NULL OR demand_threshold_percent BETWEEN 0 AND 100)
);

-- 9. RESERVATIONS: planned charger time slots
CREATE TABLE reservations (
    reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(user_id),
    vehicle_id     BIGINT NOT NULL REFERENCES vehicles(vehicle_id),
    charger_id     BIGINT NOT NULL REFERENCES chargers(charger_id),
    start_at       TIMESTAMPTZ NOT NULL,
    end_at         TIMESTAMPTZ NOT NULL,
    status         VARCHAR(20) NOT NULL DEFAULT 'CONFIRMED'
                   CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'COMPLETED', 'NO_SHOW')),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_at > start_at)
);

-- 10. CHARGING_SESSIONS: actual charging activity and meter readings
CREATE TABLE charging_sessions (
    session_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id   BIGINT UNIQUE REFERENCES reservations(reservation_id),
    user_id          BIGINT NOT NULL REFERENCES users(user_id),
    vehicle_id       BIGINT NOT NULL REFERENCES vehicles(vehicle_id),
    charger_id       BIGINT NOT NULL REFERENCES chargers(charger_id),
    tariff_id        BIGINT NOT NULL REFERENCES tariffs(tariff_id),
    started_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at         TIMESTAMPTZ,
    meter_start_kwh  NUMERIC(12,3) NOT NULL CHECK (meter_start_kwh >= 0),
    meter_end_kwh    NUMERIC(12,3),
    status           VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                     CHECK (status IN ('ACTIVE', 'COMPLETED', 'INTERRUPTED')),
    CHECK (meter_end_kwh IS NULL OR meter_end_kwh >= meter_start_kwh),
    CHECK (ended_at IS NULL OR ended_at >= started_at),
    CHECK (
        (status = 'ACTIVE' AND ended_at IS NULL AND meter_end_kwh IS NULL)
        OR
        (status IN ('COMPLETED', 'INTERRUPTED') AND ended_at IS NOT NULL AND meter_end_kwh IS NOT NULL)
    )
);

-- 11. INVOICES: final bill snapshot for a completed charging session
CREATE TABLE invoices (
    invoice_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id        BIGINT NOT NULL UNIQUE REFERENCES charging_sessions(session_id),
    energy_kwh        NUMERIC(12,3) NOT NULL CHECK (energy_kwh >= 0),
    price_per_kwh     NUMERIC(10,2) NOT NULL CHECK (price_per_kwh >= 0),
    session_fee       NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (session_fee >= 0),
    tax_rate_percent  NUMERIC(5,2) NOT NULL DEFAULT 0 CHECK (tax_rate_percent BETWEEN 0 AND 100),
    energy_charge     NUMERIC(12,2) NOT NULL CHECK (energy_charge >= 0),
    tax_amount        NUMERIC(12,2) NOT NULL CHECK (tax_amount >= 0),
    total_amount      NUMERIC(12,2) NOT NULL CHECK (total_amount >= 0),
    status            VARCHAR(20) NOT NULL DEFAULT 'UNPAID'
                      CHECK (status IN ('UNPAID', 'PAID', 'VOID')),
    issued_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 12. PAYMENTS: payment attempts against invoices
CREATE TABLE payments (
    payment_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id             BIGINT NOT NULL REFERENCES invoices(invoice_id),
    amount                 NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    payment_method         VARCHAR(20) NOT NULL DEFAULT 'DEMO'
                           CHECK (payment_method IN ('UPI', 'CARD', 'CASH', 'DEMO')),
    transaction_reference  VARCHAR(120) UNIQUE,
    status                 VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                           CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REFUNDED')),
    created_at             TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at                TIMESTAMPTZ
);

-- 13. MAINTENANCE_RECORDS: charger fault reports and repair work
CREATE TABLE maintenance_records (
    maintenance_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charger_id        BIGINT NOT NULL REFERENCES chargers(charger_id),
    reported_by       BIGINT NOT NULL REFERENCES users(user_id),
    assigned_to       BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    issue_description TEXT NOT NULL,
    priority          VARCHAR(15) NOT NULL DEFAULT 'MEDIUM'
                      CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    status            VARCHAR(20) NOT NULL DEFAULT 'OPEN'
                      CHECK (status IN ('OPEN', 'IN_PROGRESS', 'RESOLVED', 'CANCELLED')),
    reported_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    scheduled_at      TIMESTAMPTZ,
    resolved_at       TIMESTAMPTZ,
    maintenance_cost  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (maintenance_cost >= 0),
    CHECK (resolved_at IS NULL OR resolved_at >= reported_at)
);

-- 14. CHARGER_STATUS_HISTORY: audit trail of charger status changes
CREATE TABLE charger_status_history (
    history_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charger_id      BIGINT NOT NULL REFERENCES chargers(charger_id),
    previous_status VARCHAR(25),
    new_status      VARCHAR(25) NOT NULL
                    CHECK (new_status IN ('ONLINE', 'MAINTENANCE', 'OUT_OF_SERVICE')),
    changed_by      BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    reason          TEXT,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        previous_status IS NULL
        OR previous_status IN ('ONLINE', 'MAINTENANCE', 'OUT_OF_SERVICE')
    )
);

-- Supporting indexes for common lookups and joins
CREATE INDEX idx_vehicles_owner ON vehicles(owner_user_id);
CREATE INDEX idx_stations_city ON stations(city);
CREATE INDEX idx_chargers_station_status ON chargers(station_id, operational_status);
CREATE INDEX idx_tariffs_station_validity ON tariffs(station_id, valid_from, valid_to);
CREATE INDEX idx_reservations_charger_time ON reservations(charger_id, start_at, end_at);
CREATE INDEX idx_reservations_user ON reservations(user_id, start_at DESC);
CREATE INDEX idx_sessions_charger_status ON charging_sessions(charger_id, status);
CREATE INDEX idx_invoices_status ON invoices(status);
CREATE INDEX idx_payments_invoice_status ON payments(invoice_id, status);
CREATE INDEX idx_maintenance_status ON maintenance_records(status, priority);
CREATE INDEX idx_charger_history_charger_time ON charger_status_history(charger_id, changed_at DESC);

COMMIT;

-- Verify that all 14 tables were created in the public schema
SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_type = 'BASE TABLE'
ORDER BY table_name;
